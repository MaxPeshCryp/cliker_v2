// Browser regression checks use an isolated Flask server and two independent sessions.
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const {spawn} = require('node:child_process')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const net = require('node:net')
const assert = require('node:assert/strict')

;(async () => {
    const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'clicker-admin-ui-'))
    const listener = net.createServer()
    await new Promise(resolve => listener.listen(0, '127.0.0.1', resolve))
    const port = listener.address().port
    await new Promise(resolve => listener.close(resolve))
    const url = `http://127.0.0.1:${port}`
    const code = `
import app, time
from werkzeug.security import generate_password_hash
app.app.config.update(CLICKER_ADMIN_LOGIN_HASH=generate_password_hash('test-admin'),
                      CLICKER_ADMIN_PASSWORD_HASH=generate_password_hash('test-admin-password'))
original_time = time.time
offset = 0
time.time = lambda: original_time() + offset
@app.app.post('/__test__/advance')
def advance():
    global offset
    offset += app.request.get_json()['seconds']
    return {'ok': True}
app.app.run(host='127.0.0.1', port=${port}, debug=False)
`
    const child = spawn(process.env.PYTHON_EXE || 'python', ['-c', code], {
        cwd: path.resolve(__dirname, '..'), windowsHide: true,
        env: {...process.env, CLICKER_DATABASE_PATH:path.join(temporary, 'test.db'), CLICKER_SECRET_KEY:'admin-ui-test-only', CLICKER_COOKIE_SECURE:'false'},
        stdio:['ignore', 'pipe', 'pipe']
    })
    let logs = '', browser
    child.stdout.on('data', data => { logs += data })
    child.stderr.on('data', data => { logs += data })
    try {
        await new Promise((resolve, reject) => {
            const timer = setTimeout(() => reject(new Error(logs)), 15000)
            child.on('error', error => { clearTimeout(timer); reject(error) })
            child.on('exit', code => { clearTimeout(timer); reject(new Error(`Flask exited: ${code}\n${logs}`)) })
            child.stderr.on('data', () => { if (logs.includes('Running on')) { clearTimeout(timer); resolve() } })
        })
        browser = await chromium.launch({headless:true, channel:'msedge'})
        const adminContext = await browser.newContext({viewport:{width:1440, height:1100}})
        const playerContext = await browser.newContext({viewport:{width:1280, height:1000}})
        const page = await adminContext.newPage()
        const playerPage = await playerContext.newPage()
        const errors = []
        page.on('pageerror', error => errors.push(error.message))
        playerPage.on('pageerror', error => errors.push(error.message))
        playerPage.on('dialog', dialog => dialog.accept())
        const request = playerContext.request
        await request.post(`${url}/api/register`, {data:{nickname:'Игрок <script>bad()</script>', email:'admin-ui@test', password:'player-password'}})
        await request.post(`${url}/api/login`, {data:{email:'admin-ui@test', password:'player-password'}})
        assert.equal((await request.get(`${url}/api/admin/users`)).status(), 401)
        await page.goto(`${url}/admin/login`)
        await page.locator('#loginPanel').waitFor({state:'visible'})
        await page.locator('#adminLogin').fill('test-admin')
        await page.locator('#adminPassword').fill('test-admin-password')
        await page.locator('#adminLoginForm button').click()
        await page.locator('.player-item').waitFor()
        const idle = () => page.waitForFunction(() => !document.querySelector('#adminPanel').inert)
        await idle()
        await page.locator('.player-item').click()
        await page.locator('#playerPanel').waitFor({state:'visible'})
        await idle()
        assert.equal(await page.locator('#selectedName').textContent(), 'Игрок <script>bad()</script>')
        assert.equal(await page.locator('#selectedName script').count(), 0)
        assert.equal(await page.locator('#badgeChoices input').count(), 12)
        assert.equal(await page.locator('#nextPage').isDisabled(), true)
        assert.equal(await page.locator('#previousPage').isDisabled(), true)
        const exact = '10000000000000000000000000000123'
        await page.locator('#clickAmount').fill(exact)
        await page.locator('[value="add_clicks"]').click()
        await idle()
        assert.equal(await page.locator('#selectedBalance').textContent(), `${exact} кликов`)
        await page.locator('#clickAmount').fill('23')
        await page.locator('[value="remove_clicks"]').click()
        await idle()
        assert.equal(await page.locator('#selectedBalance').textContent(), `${BigInt(exact)-23n} кликов`)
        for (const checkbox of await page.locator('#badgeChoices input').all()) await checkbox.check()
        await page.locator('#grantBadges').click()
        await idle()
        let state = await (await request.get(`${url}/api/state`)).json()
        assert.equal(state.badges.length, 12)
        await playerPage.goto(url)
        await playerPage.locator('#gameLayout').waitFor({state:'visible'})
        assert.equal(await playerPage.locator('#welcomeName .player-badge').count(), 11)
        assert.equal(await playerPage.locator('#welcomeName .verified-badge').count(), 1)
        await playerPage.setViewportSize({width:390, height:844})
        assert.equal(await playerPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
        await page.locator('#revokeVerification').click()
        await idle()
        state = await (await request.get(`${url}/api/state`)).json()
        assert.equal(state.isVerified, false)
        await page.locator('#badgeChoices input[value="founder"]').check()
        await page.locator('#badgeChoices input[value="legend"]').check()
        await page.locator('#revokeBadges').click()
        await idle()
        state = await (await request.get(`${url}/api/state`)).json()
        assert.equal(state.badges.length, 9)
        await request.post(`${url}/api/robots/robot1/upgrade`)
        await page.locator('#incomeMultiplier').fill('7')
        await page.locator('#incomeDuration').fill('2')
        await page.locator('#incomeUnit').selectOption('1')
        await page.locator('#incomeForm button[type="submit"]').click()
        await idle()
        state = await (await request.get(`${url}/api/state`)).json()
        assert.equal(state.adminIncomeBoost.multiplier, 7)
        assert.equal(state.robotsIncomeGross, 70)
        await page.request.post(`${url}/__test__/advance`, {data:{seconds:3}})
        state = await (await request.get(`${url}/api/state`)).json()
        assert.equal(state.adminIncomeBoost.multiplier, 1)
        assert.equal(state.robotsIncomeGross, 10)
        await page.locator('#incomeForm button[type="submit"]').click()
        await idle()
        await page.locator('#stopIncomeBoost').click()
        await idle()
        state = await (await request.get(`${url}/api/state`)).json()
        assert.equal(state.adminIncomeBoost.remaining, 0)
        await page.locator('#toggleBan').click()
        await idle()
        assert.equal(await page.locator('#selectedStatus').textContent(), 'Заблокирован')
        const banned = await request.post(`${url}/api/login`, {data:{email:'admin-ui@test', password:'player-password'}})
        assert.equal(banned.status(), 403)
        await playerPage.locator('#form-login').waitFor({state:'visible'})
        await page.locator('#toggleBan').click()
        await idle()
        assert.equal((await request.post(`${url}/api/login`, {data:{email:'admin-ui@test', password:'player-password'}})).status(), 200)
        await page.locator('#playerSearch').fill('not-found')
        await page.locator('#searchForm button').click()
        await idle()
        assert.equal(await page.locator('.player-item').count(), 0)
        await page.locator('#playerSearch').fill('admin-ui@test')
        await page.locator('#searchForm button').click()
        await idle()
        assert.equal(await page.locator('.player-item').count(), 1)
        await page.setViewportSize({width:390, height:844})
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
        await page.locator('#resetAccount').click()
        await page.locator('#resetConfirmation').fill('999')
        await page.locator('#resetForm button[type="submit"]').click()
        assert.equal(await page.locator('#resetDialog').evaluate(dialog => dialog.open), true)
        await page.locator('#resetConfirmation').fill('1')
        await page.locator('#resetForm button[type="submit"]').click()
        await idle()
        await page.locator('#resetDialog').waitFor({state:'hidden'})
        assert.equal(await page.locator('#selectedBalance').textContent(), '0 кликов')
        assert.equal(await page.locator('#selectedBadges .badge-tag').count(), 0)
        assert.equal((await request.post(`${url}/api/login`, {data:{email:'admin-ui@test', password:'player-password'}})).status(), 200)
        state = await (await request.get(`${url}/api/state`)).json()
        assert.equal(state.progression.level, 1)
        assert.equal(state.robots.robot1.level, 0)
        if (process.env.CLICKER_SCREENSHOT_DIR) {
            fs.mkdirSync(process.env.CLICKER_SCREENSHOT_DIR, {recursive:true})
            await page.screenshot({path:path.join(process.env.CLICKER_SCREENSHOT_DIR, 'admin-mobile.png'), fullPage:true})
            await page.setViewportSize({width:1440, height:1100})
            await page.screenshot({path:path.join(process.env.CLICKER_SCREENSHOT_DIR, 'admin-desktop.png'), fullPage:true})
        }
        await page.reload()
        await page.locator('.player-item').waitFor()
        await idle()
        await page.locator('#adminLogout').click()
        await page.locator('#loginPanel').waitFor({state:'visible'})
        assert.equal((await page.request.get(`${url}/api/admin/users`)).status(), 401)
        assert.deepEqual(errors, [])
        console.log('Admin browser checks passed: access, exact clicks, 12 badges, boost expiry, ban, reset, persistence, mobile layout and logout.')
    } finally {
        if (browser) await browser.close()
        const exited = new Promise(resolve => child.once('exit', resolve))
        child.kill()
        if (child.exitCode === null) await exited
        const resolved = path.resolve(temporary)
        if (!resolved.startsWith(path.resolve(os.tmpdir()) + path.sep)) throw new Error('Unexpected temporary path')
        fs.rmSync(resolved, {recursive:true, force:true})
    }
})().catch(error => { console.error(error); process.exitCode = 1 })
